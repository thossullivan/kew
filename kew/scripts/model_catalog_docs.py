"""Generate the model-catalog mirrors: the model-eol docs list and the www view.

``kew/src/kew/models.json`` is the single source (#2532). Two files copy it:

* ``docs/cli/model-eol.md`` carries the model list between the
  ``kew:model-list`` marker comments. Text outside the markers is hand-written
  and left byte-for-byte alone.
* ``www/src/lib/data/model-lifecycle.json`` is the site's lifecycle view: the
  catalog rows for every id the committed config routes or prices, with
  ``routed`` derived from ``kew.toml`` and ``priced`` from the catalog's
  OpenRouter-priced rows (``price_source: "openrouter"`` with a price).

Neither is edited by hand. ``tests/test_model_catalog_docs.py`` compares both
files to this script's output and names the command below when they differ.

    uv run python scripts/model_catalog_docs.py           rewrite both files
    uv run python scripts/model_catalog_docs.py --check   read-only, exit 1 on drift

Run from ``kew/``. Rendering is deterministic: the same committed inputs always
produce the same bytes, and there is no build-time date stamp.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from kew.model_catalog import ModelCatalog, ModelRow, parse_catalog

REGENERATE_COMMAND = "cd kew && uv run python scripts/model_catalog_docs.py"

ROOT = Path(__file__).resolve().parents[2]
CATALOG = Path("kew/src/kew/models.json")
DOCS_PAGE = Path("docs/cli/model-eol.md")
WWW_VIEW = Path("www/src/lib/data/model-lifecycle.json")
ROUTING = Path("kew.toml")

BEGIN_MARKER = (
    "<!-- kew:model-list:begin (generated by kew/scripts/model_catalog_docs.py;"
    " do not edit) -->"
)
END_MARKER = "<!-- kew:model-list:end -->"
VIEW_SCHEMA = "kew/model-lifecycle-view@1"

# The same line shapes the site's build check reads (www/scripts/
# fetch-model-lifecycle.mjs): any uncommented `model = "..."` assignment.
_MODEL_VALUE = re.compile(r'^\s*[^#\n]*?\bmodel\s*=\s*"([^"]+)"', re.MULTILINE)


class DriftError(RuntimeError):
    """A generated file is missing, malformed, or differs from the catalog."""


def _load_catalog(root: Path) -> ModelCatalog:
    return parse_catalog(json.loads((root / CATALOG).read_text(encoding="utf-8")))


def _cell(value: str | None) -> str:
    return f"`{value}`" if value else ""


def _table_row(row: ModelRow) -> str:
    lifecycle = row.lifecycle
    aliases = ", ".join(f"`{alias}`" for alias in row.aliases)
    cells = (
        f"`{row.id}`",
        aliases,
        row.provider,
        lifecycle.status,
        lifecycle.shutdown or "",
        _cell(lifecycle.replacement),
    )
    return "| " + " | ".join(cells) + " |"


def render_model_list(catalog: ModelCatalog) -> str:
    """The marked block for the docs page, markers included."""
    count = len(catalog.rows)
    noun = "model" if count == 1 else "models"
    lines = [
        BEGIN_MARKER,
        "",
        f"The catalog lists {count} {noun}, last reviewed"
        f" {catalog.reviewed_at.isoformat()}.",
        "",
        "| Model | Aliases | Provider | Status | Shutdown | Replacement |",
        "| --- | --- | --- | --- | --- | --- |",
        *(_table_row(row) for row in catalog.rows),
        "",
        END_MARKER,
    ]
    return "\n".join(lines)


def render_docs_page(page: str, catalog: ModelCatalog) -> str:
    """``page`` with the text between its markers replaced by the model list."""
    if page.count(BEGIN_MARKER) != 1 or page.count(END_MARKER) != 1:
        raise DriftError(
            f"{DOCS_PAGE} needs exactly one {BEGIN_MARKER!r} and one {END_MARKER!r}"
        )
    start = page.index(BEGIN_MARKER)
    end = page.index(END_MARKER) + len(END_MARKER)
    if end < start:
        raise DriftError(f"{DOCS_PAGE} has its end marker before its begin marker")
    return page[:start] + render_model_list(catalog) + page[end:]


def render_www_view(catalog: ModelCatalog, routing: str) -> str:
    """The site's lifecycle view, as the committed JSON text."""
    routed = set(_MODEL_VALUE.findall(routing))
    # The rows `kew models refresh` prices from OpenRouter, as the site's
    # build check reads them (www/scripts/fetch-model-lifecycle.mjs).
    priced = {
        row.id
        for row in catalog.rows
        if row.price_source == "openrouter" and row.price is not None
    }
    ids = sorted(routed | priced)
    if not ids:
        raise DriftError(
            "no routed or priced model ids in the committed config and catalog"
        )
    rows = {row.id: row for row in catalog.rows}
    missing = [model_id for model_id in ids if model_id not in rows]
    if missing:
        raise DriftError(
            f"{CATALOG} has no row for {len(missing)} selected model id(s): "
            f"{', '.join(missing)}. Add the row before regenerating."
        )
    unevidenced = [i for i in ids if not rows[i].lifecycle.evidence]
    if unevidenced:
        raise DriftError(
            f"selected model id(s) with no lifecycle evidence: {', '.join(unevidenced)}"
        )
    view = {
        "schema": VIEW_SCHEMA,
        "reviewedAt": catalog.reviewed_at.isoformat(),
        "models": [_view_row(rows[i], i in routed, i in priced) for i in ids],
    }
    return json.dumps(view, indent=2, ensure_ascii=False) + "\n"


def _view_row(row: ModelRow, routed: bool, priced: bool) -> dict[str, object]:
    lifecycle = row.lifecycle
    return {
        "id": row.id,
        "provider": row.provider,
        "status": lifecycle.status,
        "shutdown": lifecycle.shutdown,
        "replacement": lifecycle.replacement,
        "evidence": [
            {"kind": item.kind, "url": item.url, "checkedAt": item.checked_at}
            for item in lifecycle.evidence
        ],
        "routed": routed,
        "priced": priced,
    }


def render(root: Path = ROOT) -> dict[Path, str]:
    """Every generated file under ``root``, keyed by its repo-relative path."""
    catalog = _load_catalog(root)
    page = (root / DOCS_PAGE).read_text(encoding="utf-8")
    return {
        DOCS_PAGE: render_docs_page(page, catalog),
        WWW_VIEW: render_www_view(
            catalog, (root / ROUTING).read_text(encoding="utf-8")
        ),
    }


def stale_files(root: Path = ROOT) -> list[Path]:
    """The generated files under ``root`` whose committed text differs."""
    stale = []
    for path, text in render(root).items():
        target = root / path
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            stale.append(path)
    return stale


def check(root: Path = ROOT) -> None:
    """Raise :class:`DriftError` naming the regenerate command on any drift."""
    stale = stale_files(root)
    if stale:
        names = ", ".join(str(path) for path in stale)
        raise DriftError(
            f"{names} differ from {CATALOG}; run `{REGENERATE_COMMAND}`"
            " and commit the result"
        )


def write(root: Path = ROOT) -> list[Path]:
    """Rewrite every stale generated file; return the paths written."""
    written = []
    for path, text in render(root).items():
        target = root / path
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            target.write_text(text, encoding="utf-8")
            written.append(path)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="exit 1 instead of rewriting on drift"
    )
    args = parser.parse_args(argv)
    try:
        if args.check:
            check()
            print("model catalog mirrors match the catalog")
        else:
            written = write()
            for path in written:
                print(f"wrote {path}")
            if not written:
                print("model catalog mirrors already match the catalog")
    except DriftError as exc:
        print(f"model catalog mirrors: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
